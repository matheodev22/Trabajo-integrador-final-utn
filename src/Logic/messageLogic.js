export const createMessage = (text) => {
  const cleanText = text?.trim();

  if (!cleanText) {
    return null;
  }

  return {
    id: Date.now(),
    text: cleanText,
    sender: "sent",
    time: new Date().toLocaleTimeString(
      [],
      {
        hour: "2-digit",
        minute: "2-digit",
      }
    ),
    status: "sent",
  };
};




export const addMessage = (
  messages,
  chatId,
  message
) => {
  return {
    ...messages,

    [chatId]: [
      ...(messages[chatId] || []),
      message,
    ],
  };
};




export const editMessage = (
  messages,
  chatId,
  messageId,
  newText
) => {
  const cleanText = newText?.trim();

  if (!cleanText) {
    return messages;
  }

  return {
    ...messages,

    [chatId]: (
      messages[chatId] || []
    ).map((message) =>
      message.id === messageId
        ? {
            ...message,
            text: cleanText,
            edited: true,
          }
        : message
    ),
  };
};



export const deleteMessage = (
  messages,
  chatId,
  messageId
) => {
  return {
    ...messages,

    [chatId]: (
      messages[chatId] || []
    ).filter(
      (message) =>
        message.id !== messageId
    ),
  };
};





export const markMessagesAsRead = (
  messages,
  chatId
) => {
  if (!messages[chatId]) {
    return messages;
  }

  return {
    ...messages,

    [chatId]: messages[chatId].map(
      (message) =>
        message.sender === "received"
          ? {
              ...message,
              status: "read",
            }
          : message
    ),
  };
};